"""Testes dos cortes FIM por limite sintatico em JS generico (replay_cuts.py) e das guardas de licenca do build_replay.py."""
import random
import sys
from pathlib import Path

import pytest

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))

import build_replay as br  # noqa: E402
import replay_cuts as rcuts  # noqa: E402

TOKENIZER = rcuts.ROOT / "BaseRepos" / "Qwen2.5-Coder-7B" / "tokenizer.json"

SAMPLE = """'use strict'
const path = require('path')

/**
 * Resolve a list of names into absolute paths.
 */
function resolveAll (names, base) {
  const out = []
  for (const name of names) {
    if (!name) continue
    out.push(path.resolve(base, name.trim()))
  }
  return out.filter(Boolean)
}

const defaults = {
  base: process.cwd(),
  names: ['a', 'b', 'c'],
  verbose: false,
}

module.exports = function run (opts = {}) {
  const cfg = Object.assign({}, defaults, opts)
  const paths = resolveAll(cfg.names, cfg.base)
  if (cfg.verbose) console.log(paths.join(', '))
  return paths.map((p) => p.toUpperCase())
}
"""


@pytest.fixture(scope="module")
def tc():
    if not TOKENIZER.exists():
        pytest.skip("tokenizer do base ausente")
    return rcuts.Counter96(str(TOKENIZER))


def test_spans_have_expected_roles():
    roles = {r for _s, _e, r, _u in rcuts.js_spans(SAMPLE)}
    assert {"member", "value", "key", "chain", "stmt", "obj"} <= roles


def test_cuts_reconstruct_document_and_respect_limits(tc):
    cuts = 0
    for seed in range(40):
        c = rcuts.make_cut(SAMPLE, random.Random(seed), tc, max_tokens=96, min_prefix_chars=20)
        if c is None:
            continue
        cuts += 1
        assert c["prefix"] + c["middle"] + c["suffix"] == SAMPLE
        assert c["middle"].strip() and any(ch.isalnum() for ch in c["middle"])
        assert tc.count(c["middle"]) <= 96
        assert c["cut_kind"] in rcuts.KIND_WEIGHTS
    assert cuts >= 30


def test_cuts_are_deterministic(tc):
    a = rcuts.make_cut(SAMPLE, random.Random(7), tc, min_prefix_chars=20)
    b = rcuts.make_cut(SAMPLE, random.Random(7), tc, min_prefix_chars=20)
    assert a == b


def test_unlexable_text_returns_none(tc):
    assert rcuts.make_cut("const s = 'unterminated\nfoo()\n" * 5, random.Random(1), tc) is None


@pytest.mark.parametrize("expr,ok", [("MIT", True), ("Apache-2.0", True), ("ISC", True), ("(MIT OR GPL-3.0)", True),
                                     ("(Apache-2.0 AND BSD-3-Clause)", True), ("GPL-3.0", False), ("MIT AND GPL-2.0", False),
                                     ("SEE LICENSE IN LICENSE.md", False), ("CC-BY-4.0", False), ("Artistic-2.0", False)])
def test_spdx_policy(expr, ok):
    assert br.spdx_ok(expr)[0] is ok


def test_file_filter_rejects_minified_gpl_and_secrets():
    body = "\n".join(f"const value{i} = compute({i}) // line {i}" for i in range(40))
    assert br.file_filter(body, "ok.js")[0]
    assert br.file_filter("x=1;" * 5000 + "\n" * 20, "min.js") == (False, "minified_or_bundle")
    assert br.file_filter(body + "\n// GNU General Public License v3\n", "gpl.js")[1] == "copyleft_or_proprietary_text"
    assert br.file_filter(body + "\nconst k = 'AKIAABCDEFGHIJKLMNOP'\n", "key.js")[1] == "secret"
    assert br.file_filter("a\nb\n", "short.js") == (False, "lt15_lines")
    assert br.file_filter(body + "\n// @generated by tool\n", "gen.js")[1] == "generated"
